#!/usr/bin/env python3
"""Embed the editable Diffusion Studio shader in both hosts without divergence."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
design = root / 'design' / 'pearl-cloud'
parser = argparse.ArgumentParser()
parser.add_argument('--native', action='store_true', help='also update the native plugin header')
parser.add_argument('--check', action='store_true', help='verify instead of writing')
args = parser.parse_args()
source = (design / 'pearl-cloud.glsl').read_text()
files = {design / 'shader.ts': '// Generated by scripts/sync-pearl-cloud.py. Edit pearl-cloud.glsl.\nexport default ' + json.dumps(source) + ';\n'}
if args.native:
    files[root / 'Source' / 'PearlCloudShader.h'] = '#pragma once\n\n// Generated by scripts/sync-pearl-cloud.py. Edit design/pearl-cloud/pearl-cloud.glsl.\ninline const char* pearlCloudFunctions = R"GLSL(\n' + source + ')GLSL";\n'
for path, content in files.items():
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Out-of-date shader: {path}')
    else:
        path.write_text(content)
print('Pearl Cloud shader hosts are synchronized.' if args.check else 'Pearl Cloud shader embedded.')
